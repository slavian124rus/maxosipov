import { expect, test } from 'vitest'
import { detectFlag, PAIN_REPLY } from './flags'

const cases: [string, 'pain' | 'injury' | null][] = [
  ['болит колено', 'pain'],
  ['потянул спину, кажется растяжение', 'injury'],
  ['тянет поясницу', 'pain'],
  ['тянет время', null],
  ['мышцы болят после тренировки', null],
  ['крепатура жесть', null],
  ['хрустит плечо при жиме', 'pain'],
  ['вчера был перелом пальца', 'injury'],
  ['ноет плечо после жима', 'pain'],
  ['онемел мизинец на левой руке', 'pain'],
  ['прострелило в спине', 'pain'],
  ['больно жать лёжа', 'pain'],
  ['порвал связку на ноге', 'injury'],
  ['вывих плеча', 'injury'],
  ['защемило шею', 'injury'],
  ['надорвал бицепс', 'injury'],
  ['большой вес взял', null],
  ['забились мышцы после тренировки', null],
  ['спина забилась, крепатура', null],
  ['БОЛИТ КОЛЕНО', 'pain'],
  ['щиколотка болит', 'pain'],
  ['колено болит после тренировки', 'pain'],
  ['тянет низ живота', null],
  ['щемит в груди', 'pain'],
  ['кружится голова после подхода', 'pain'],
  ['давит в груди на жиме', 'pain'],
  ['подозрение на грыжу', 'injury'],
  ['перерыв между подходами 2 минуты', null],
  ['травмпункт рядом', 'injury'],
]

for (const [text, expected] of cases) {
  test(`detectFlag: «${text}» → ${expected ?? 'null'}`, () => {
    expect(detectFlag(text)).toBe(expected)
  })
}

test('ответ на боль — дословно из плана', () => {
  expect(PAIN_REPLY).toBe('Остановись. Это лучше показать Максиму — я ему передал.')
})
